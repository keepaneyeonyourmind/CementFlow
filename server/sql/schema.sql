-- Учебная схема. Запускать в отдельной учебной базе PostgreSQL.
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    unit VARCHAR(50) NOT NULL,
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    product_name VARCHAR(150) NOT NULL,
    unit VARCHAR(50) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10000),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    total NUMERIC(16, 2) NOT NULL CHECK (total >= 0),
    customer_name VARCHAR(100) NOT NULL CHECK (length(trim(customer_name)) > 0),
    phone VARCHAR(100) NOT NULL CHECK (length(trim(phone)) > 0),
    address VARCHAR(300) NOT NULL CHECK (length(trim(address)) > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING', 'ASSIGNED', 'IN_TRANSIT', 'DELIVERED')),
    driver_name VARCHAR(100),
    CHECK ((status = 'WAITING' AND driver_name IS NULL) OR (status <> 'WAITING' AND driver_name IS NOT NULL AND length(trim(driver_name)) > 0))
);
